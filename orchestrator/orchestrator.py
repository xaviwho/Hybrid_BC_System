def get_windows_host_ip():
    """
    Parses the WSL resolv.conf file to get the Windows host IP address.
    This is necessary for services inside WSL to connect to services on the host.
    """
    try:
        # This file is auto-generated by WSL and contains the host's IP
        with open("/etc/resolv.conf") as f:
            for line in f:
                if line.strip().startswith("nameserver"):
                    return line.split()[1]
    except FileNotFoundError:
        # This will happen if not running in a standard WSL environment
        return None

